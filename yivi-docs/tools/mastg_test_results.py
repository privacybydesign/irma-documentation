#!/usr/bin/env python3
"""Writes edi-stelsel/conformance/owasp-mas-eudiw-tests.md from the results of the test bed.

The test bed lives in privacybydesign/irmamobile (mastg/testbed.py). Each run writes
docs-results.json; copy that file to src/data/edi-stelsel/mastg-results.json and run:

    python3 tools/mastg_test_results.py

The page has one anchor per requirement (#req-26) and one per test
(#mastg-test-0204, #yivi-test-0001). The test bed links to these anchors, so do not
change how they are formed.
"""

from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "src/data/edi-stelsel/mastg-results.json"
PAGE = ROOT / "edi-stelsel/conformance/owasp-mas-eudiw-tests.md"
CATALOGUE_PAGE = ROOT / "edi-stelsel/requirements/owasp-mas-eudiw.md"
CATALOGUE = "/edi-stelsel-certification/requirements/owasp-mas-eudiw"
CONFORMANCE = "/edi-stelsel-certification/conformance/owasp-mas-eudiw"

LABEL = {
    "pass": "Pass",
    "not_applicable": "Not applicable",
    "fail": "Fail",
    "triage": "To triage",
    "not_automated": "Not automated",
}
ORDER = ["pass", "not_applicable", "fail", "triage", "not_automated"]
RESOLVED = {"pass", "not_applicable"}
# The longest piece of matched text shown for a finding.
MAX_FINDING_TEXT = 140


def code(text: str) -> str:
    return "`" + text.replace("`", "'").replace("\n", " ") + "`"


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def weaknesses() -> dict[int, str]:
    """The link to the OWASP weakness (MASWE) of each requirement, from the catalogue page."""
    links, number = {}, None
    for line in CATALOGUE_PAGE.read_text(encoding="utf-8").splitlines():
        heading = re.match(r"^### \\#(\d+) ", line)
        if heading:
            number = int(heading.group(1))
        weakness = re.match(r"^\*\*MASWE:\*\* (\[.*\]\(https://mas\.owasp\.org/\S+\))", line)
        if weakness and number:
            links[number] = weakness.group(1)
    return links


def test_link(test: dict) -> str:
    return f"[{test['id']}](#{test['id'].lower()})"


def numbers(test: dict) -> str:
    return ", ".join(f"[#{number}](#req-{number})" for number in test["requirements"])


def check_lines(test: dict) -> list[str]:
    lines = []
    for check in test["checks"]:
        who = "OWASP check" if check["origin"] == "owasp" else "Yivi check"
        line = f"- **{who}:** [`{check['id']}`]({check['source_url']}), {LABEL[check['status']].lower()}"
        if check.get("title") and check["origin"] == "yivi":
            line += f". {check['title']}"
        if check["detail"]:
            line += f" Result: {check['detail']}."
        lines.append(line)
        for key, name in (("issues", "Defect"), ("open", "To triage")):
            for item in check[key]:
                place = item["path"] + (f":{item['line']}" if item["line"] else "")
                lines.append(f"  - {name}: {code(item['text'][:MAX_FINDING_TEXT])} in {code(place)}")
            more = check.get(key + "_count", len(check[key])) - len(check[key])
            if more > 0:
                lines.append(f"  - and {more} more of this kind")
    return lines


def main() -> None:
    data = json.loads(DATA.read_text(encoding="utf-8"))
    meta, score, tests = data["meta"], data["score"], data["tests"]
    owasp = sorted((test for test in tests.values() if test["origin"] == "owasp"), key=lambda test: test["id"])
    own = sorted((test for test in tests.values() if test["origin"] == "yivi"), key=lambda test: test["id"])
    by = score["owasp_checked_by"]
    repo, commit, ref = meta["repository_url"], meta["commit"], meta["mastg_ref"]

    weakness = weaknesses()

    out: list[str] = []
    w = out.append
    w(f"""---
title: "Test results for the OWASP MAS EUDI Wallet profile"
sidebar_label: "OWASP MAS EUDIW test results"
description: "The results of the automated test bed that runs the OWASP MASTG tests of the OWASP MAS EUDI Wallet profile, and our own tests, against the Yivi app."
format: md
---

<!-- GENERATED by tools/mastg_test_results.py from src/data/edi-stelsel/mastg-results.json. Do not edit by hand. -->

This page shows the results of the test bed that tests the Yivi app against the [OWASP MAS EUDI Wallet profile]({CATALOGUE}). The test bed runs in the status checks of the app and writes these results; nobody fills them in by hand. The [conformance page]({CONFORMANCE}) gives the assessment per requirement.

:::caution[Not a certification result]

These are the results of our own automated test bed. They are not the result of an evaluation by a laboratory. A test that passes means that the check found no problem, not that an evaluator accepted the requirement as met.

:::

## What is from OWASP and what is from Yivi {{#origin}}

Every test and every check on this page says where it comes from.

| Label | Where it comes from | What it means |
|---|---|---|
| **OWASP test** | A test of the [OWASP MASTG](https://mas.owasp.org/MASTG/tests/), taken from the OWASP repository | The test and its pass criterion are OWASP's. The identifier starts with `MASTG-TEST-`, and every such test here links to the original on mas.owasp.org. |
| **OWASP check** | A semgrep rule from the OWASP repository, run unchanged | OWASP's own automation of its test. The link goes to the rule in the OWASP repository. |
| **Yivi check** | Written by the Yivi team | Our automation of an OWASP test that OWASP has no usable automation for. OWASP did not write or review it. |
| **Yivi test** | Written by the Yivi team | A test of our own for a requirement, not an OWASP test. The identifier starts with `YIVI-TEST-`. These are counted apart from the OWASP tests. |

Which OWASP tests belong to a requirement follows from OWASP's data: the profile gives each requirement a weakness (MASWE), and every MASTG test names the weaknesses it tests. How a finding of an OWASP rule becomes a pass or a fail is set by us, in [`config.json`]({repo}/blob/{commit}/mastg/config.json).

## Basis {{#basis}}

- **Tested:** {meta['target']}, on {meta['date']}.
- **App:** [privacybydesign/irmamobile]({repo}) at commit [`{commit[:7]}`]({repo}/commit/{commit}).""" + (f" [CI run]({meta['run_url']})." if meta.get("run_url") else "") + f"""
- **OWASP MASTG:** commit [`{ref[:7]}`](https://github.com/OWASP/mastg/commit/{ref}).
- **Profile:** OWASP MAS EUDI Wallet profile {meta['profile']}.
- **Test bed:** [`mastg/`]({repo}/tree/{commit}/mastg) in the app repository.

## Score {{#score}}

**OWASP tests: {score['owasp']['score']}%.** {score['owasp']['resolved']} of the {score['owasp']['tests']} OWASP tests in the profile are resolved, which means pass or not applicable.

**Automation: {score['owasp']['automation']}%.** {score['owasp']['automated']} of the {score['owasp']['tests']} OWASP tests have a check. {by.get('owasp_checks_only', 0)} are checked by OWASP's own rules, {by.get('yivi_checks_only', 0)} by our own checks, {by.get('both', 0)} by both, and {by.get('recorded_verdict', 0)} have a recorded verdict without a check.

**Yivi tests: {score['yivi']['resolved']} of {score['yivi']['tests']} resolved.** These are not part of the OWASP score.

| Status | OWASP tests, Android | OWASP tests, iOS | OWASP tests, other | Yivi tests |
|---|---|---|---|---|
""")

    for status in ORDER:
        row = Counter(test["platform"] if test["platform"] in ("android", "ios") else "other"
                      for test in owasp if test["status"] == status)
        mine = sum(1 for test in own if test["status"] == status)
        w(f"| {LABEL[status]} | {row['android']} | {row['ios']} | {row['other']} | {mine} |\n")

    w("""
| Status | Meaning |
|---|---|
| Pass | The check ran and found no problem. |
| Not applicable | Recorded by hand, with a reason. |
| Fail | A check found a defect, or did not find the protection it looks for. |
| To triage | A check found something a person has to judge. |
| Not automated | No check runs for this test yet. |

The checks read the Java code, the manifests and the native binaries of the app. The Dart and Go code, which holds most of the logic of Yivi, is compiled to machine code and is only covered where a Yivi test reads the sources.

## Results per requirement {#requirements}

The number links to the requirement in the catalogue. The counts are OWASP tests.

| # | Requirement | OWASP tests | Pass | N/A | Fail | To triage | Not automated | Yivi tests |
|---|---|---|---|---|---|---|---|---|
""")

    for requirement in data["requirements"]:
        counts = Counter(tests[test_id]["status"] for test_id in requirement["tests"])
        figures = " | ".join(str(counts[status] or "") for status in ORDER)
        mine = requirement["yivi_tests"]
        done = sum(1 for test_id in mine if tests[test_id]["status"] in RESOLVED)
        w(f"| [{requirement['number']}](#req-{requirement['number']}) | {cell(requirement['title'])} | "
          f"{len(requirement['tests']) or '–'} | {figures} | {f'{done} of {len(mine)} resolved' if mine else ''} |\n")

    w("\n## Tests per requirement {#tests-per-requirement}\n")
    category = None
    for requirement in data["requirements"]:
        if requirement["category"] != category:
            category = requirement["category"]
            w(f"\n### {category} {{#{category.lower()}}}\n")
        number = requirement["number"]
        w(f"\n#### \\#{number} — {requirement['title']} {{#req-{number}}}\n\n")
        w(f"[Requirement text]({CATALOGUE}#r{number}) · [Assessment]({CONFORMANCE}#c{number})\n\n")
        if number in weakness:
            w(f"OWASP weakness: {weakness[number]}\n\n")
        if not requirement["tests"] and not requirement["yivi_tests"]:
            w("No OWASP test exists for this requirement, and we have no test of our own for it yet.\n")
            continue
        if not requirement["tests"]:
            w("No OWASP test exists for this requirement.\n\n")
        for test_id in requirement["tests"]:
            test = tests[test_id]
            w(f"- OWASP test {test_link(test)} ({test['platform']}): {test['title']}. **{LABEL[test['status']]}** "
              f"([original on mas.owasp.org]({test['url']}))\n")
        for test_id in requirement["yivi_tests"]:
            test = tests[test_id]
            w(f"- Yivi test {test_link(test)}: {test['title']}. **{LABEL[test['status']]}**\n")

    w("\n## OWASP tests {#owasp-tests}\n\nThe tests of the OWASP MASTG that belong to the profile. "
      "Each one links to the original test on the OWASP site, "
      "which has its steps and its pass criterion.\n")
    for test in owasp:
        w(f"\n#### {test['id']} {{#{test['id'].lower()}}}\n\n")
        w(f"- **OWASP test:** {test['title']}, {test['platform']}, {', '.join(test['type'])}\n")
        w(f"- **Original:** [{test['id']} on mas.owasp.org]({test['url']})\n")
        w(f"- **Requirement:** {numbers(test)}\n")
        w(f"- **Status:** {LABEL[test['status']]}\n")
        if test.get("recorded"):
            w(f"- **Recorded verdict:** {test['recorded']}\n")
        for line in check_lines(test):
            w(line + "\n")

    w("\n## Yivi tests {#yivi-tests}\n\nOur own tests. OWASP did not write or review them. They are defined in "
      f"[`yivi-tests.json`]({repo}/blob/{commit}/mastg/yivi-tests.json).\n")
    for test in own:
        w(f"\n#### {test['id']} {{#{test['id'].lower()}}}\n\n")
        w(f"- **Yivi test:** {test['title']}\n")
        w(f"- **What it tests:** {test['description']}\n")
        w(f"- **Requirement:** {numbers(test)}\n")
        w(f"- **Status:** {LABEL[test['status']]}\n")
        if test.get("recorded"):
            w(f"- **Recorded verdict:** {test['recorded']}\n")
        for line in check_lines(test):
            w(line + "\n")

    PAGE.write_text("".join(out), encoding="utf-8")
    print(f"Wrote {PAGE.relative_to(ROOT)}: {len(owasp)} OWASP tests, {len(own)} Yivi tests")


if __name__ == "__main__":
    main()
